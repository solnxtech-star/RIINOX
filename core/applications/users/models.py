class DocumentTemplate(TimeBasedModel):
    """
    Represents a document template that organizations can use for invoices,
    receipts, quotes, and credit notes. Templates define the layout and style
    of the documents generated by the system.
    """

    name = CharField(max_length=100, unique=True)
    description = TextField(blank=True, null=True)
    template_type = CharField(
        _("Template Type"),
        max_length=20,
        choices=TEMPLATE_TYPES.choices,
        default=TEMPLATE_TYPES.INVOICE,
    )
    file = FileField(
        upload_to=MediaHelper.get_template_upload_path,
        help_text=_("The actual template file (e.g. HTML, DOCX)."),
    )
    is_active = BooleanField(default=True)

    class Meta(auto_prefetch.Model.Meta):
        verbose_name = _("Document Template")
        verbose_name_plural = _("Document Templates")
        ordering = ["name"]

    def __str__(self):
        return f"{self.name} ({self.template_type})"


class Organization(TimeBasedModel):
    """
    Represents a tenant in the SaaS system.
    Each organization can customize branding and document templates.
    """

    name = CharField(max_length=255)
    type = CharField(
        _("Organization Type"),
        max_length=50,
        choices=OrganizationTypeChoices.choices,
        default=OrganizationTypeChoices.BUSINESS,
    )
    domain = CharField(
        _("Custom Domain"),
        max_length=255,
        blank=True,
        null=True,
        help_text=_("Optional custom domain (e.g. acme.com)."),
    )

    plan = auto_prefetch.ForeignKey(
        "users.Plan",
        on_delete=CASCADE,
        related_name="organizations",
        default=1,
    )
    is_active = BooleanField(_("Active"), default=True)

    # Branding
    logo = ImageField(
        upload_to=MediaHelper.get_image_upload_path,
        blank=True,
        null=True,
        help_text=_("Logo to display on invoices and receipts."),
    )
    header_text = CharField(
        max_length=255,
        blank=True,
        null=True,
        help_text=_("Custom header text (e.g. company slogan)."),
    )
    footer_text = CharField(
        max_length=255,
        blank=True,
        null=True,
        help_text=_("Custom footer text (e.g. payment instructions)."),
    )

    # Template assignments
    invoice_template = auto_prefetch.ForeignKey(
        "users.DocumentTemplate",
        on_delete=SET_NULL,
        null=True,
        blank=True,
        related_name="invoice_organizations",
        limit_choices_to={"template_type": "invoice", "is_active": True},
        help_text=_("Selected invoice template for this organization."),
    )
    receipt_template = auto_prefetch.ForeignKey(
        "users.DocumentTemplate",
        on_delete=SET_NULL,
        null=True,
        blank=True,
        related_name="receipt_organizations",
        limit_choices_to={"template_type": "receipt", "is_active": True},
        help_text=_("Selected receipt template for this organization."),
    )

    class Meta(auto_prefetch.Model.Meta):
        verbose_name = _("Organization")
        verbose_name_plural = _("Organizations")
        ordering = ["name"]

    def __str__(self):
        return self.name


