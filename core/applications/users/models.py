class User(AbstractUser):
    """
    Custom user model for Invoice Management System.
    Email is used as the unique identifier instead of username.
    """

    first_name = None  # type: ignore
    last_name = None  # type: ignore
    username = None  # type: ignore

    # id = UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    name = CharField(_("Full Name"), max_length=255, blank=True)
    email = EmailField(_("Email Address"), unique=True, db_index=True)
    address = TextField(_("Address"), blank=True, null=True)
    is_active = BooleanField(_("Active"), default=True)
    is_verified = BooleanField(_("Verified"), default=False)

    USERNAME_FIELD = "email"
    REQUIRED_FIELDS = []

    objects: ClassVar[UserManager] = UserManager()

    class Meta:
        verbose_name = _("User")
        verbose_name_plural = _("Users")
        ordering = ["-date_joined"]

    def __str__(self):
        return f"{self.name or self.email}"

    def get_absolute_url(self):
        return reverse("users:detail", kwargs={"pk": self.pk})

    @property
    def organizations(self):
        """Return all organizations the user is a member of."""
        return Organization.objects.filter(memberships__user=self)


class Membership(TimeBasedModel):
    """
    Membership ties a User to an Organization with a specific role.
    This enables multi-tenancy where users can belong to multiple orgs.
    """

    user = auto_prefetch.ForeignKey(
        "users.User",
        on_delete=CASCADE,
        related_name="memberships",
        null=True,
        blank=True,
    )
    organization = auto_prefetch.ForeignKey(
        "users.Organization",
        on_delete=CASCADE,
        related_name="memberships",
    )
    role = CharField(
        _("Role"),
        max_length=20,
        choices=UsersRole.choices,
        default=UsersRole.OWNER,
    )
    is_active = BooleanField(default=True)

    # Invitation fields
    invited_email = EmailField(
        _("Invited Email"),
        null=True,
        blank=True,
        help_text=_("The email address that received the invitation."),
    )
    invite_token = UUIDField(
        default=uuid.uuid4,
        unique=True,
        editable=False,
        help_text=_("Unique token for invitation acceptance."),
    )
    accepted = BooleanField(
        default=False,
        help_text=_("Has the invited user accepted the invitation?"),
    )
    expires_at = DateTimeField(
        default=default_invite_expiry,
        help_text=_("Expiration datetime for the invitation."),
    )

    class Meta(auto_prefetch.Model.Meta):
        verbose_name = _("Membership")
        verbose_name_plural = _("Memberships")
        unique_together = ("user", "organization")
        indexes = [
            Index(fields=["organization", "role"]),
        ]

    def __str__(self):
        if self.user:
            return f"{self.user.email} in {self.organization.name} as {self.role}"
        return f"Invitation for {self.invited_email} to {self.organization.name} as {self.role}"


